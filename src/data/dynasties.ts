/**
 * 中国历史长河 · 18 个时代节点内置数据
 *
 * category 色标体系（与 style.css / LegendBar 对应）：
 *  origin  文明源头（古铜）—— 夏、商
 *  unified 大一统 / 强盛（金）—— 周、汉、唐、宋（局部统一）、明、清
 *  chaos   大乱世 / 大分裂（暗红）—— 春秋战国、三国、两晋、南北朝、五代十国
 *  sweeper 短命清道夫（紫）—— 秦、隋、元
 *  modern  近现代（亮蓝=民国 / 正红=共和国，经 color 覆盖）
 */

export type Category = 'origin' | 'unified' | 'chaos' | 'sweeper' | 'modern'

export interface DynastyMoment {
  /** 年代刻度（如「前221」「约前1300」） */
  year: string
  text: string
}

export interface Dynasty {
  id: string
  /** 显示名（完整） */
  name: string
  /** 印章节点上的字（1-2 字） */
  seal: string
  /** 悬停提示用短时间 */
  shortYears: string
  /** 面板完整时间描述 */
  period: string
  /** 存续说明（如「享国十五年」） */
  reignNote: string
  startYear: number
  endYear: number
  /** 是否延续至今（共和国） */
  ongoing?: boolean
  /**
   * 时间轴色带覆盖的起止年份（默认与 start/end 相同）。
   * 周朝整段节点含东周，但轴上东周段由「春秋战国」带呈现，故色带只画到前 770；
   * 两晋色带自 280 年灭吴起画，避免与三国带重叠（266-280 司马炎代魏但天下仍三分）。
   */
  bandStart?: number
  bandEnd?: number
  category: Category
  /** 分类默认色之外的覆盖色（近现代红/蓝） */
  color?: string
  tags: string[]
  /** 220-260 字史略正文（面板「史略」段） */
  summary: string
  /** 大事刻度（面板竖排时间线，4 条左右） */
  moments?: DynastyMoment[]
  /** 代表人物（面板「其人」章） */
  figures?: string[]
  /** 史籍引言（面板「史籍一言」段） */
  quote?: { text: string; source: string }
  /** 「乱世与大一统」主题点评 */
  commentary: string
}

export interface CategoryMeta {
  label: string
  desc: string
  color: string
}

